"""Optional durable launch policy, independent of any application plugin."""
from dataclasses import dataclass, field
from typing import Any, Protocol

from .models import AgentInfo


@dataclass(frozen=True)
class LaunchPlan:
    name: str
    workspace: str
    runtime_spec: dict[str, Any]
    env_vars: dict[str, str]
    mounts: list[dict[str, Any]]
    instance_id: str | None = None
    needs_reconciliation: bool = False
    receipt: dict[str, Any] = field(default_factory=dict, repr=False)


class InstanceLifecycle(Protocol):
    ready_timeout: float
    def pending_delete(self, user_id: str) -> AgentInfo | None: ...
    def transport_headers(self, user_id: str) -> dict[str, str]: ...
    async def sign_request(self, user_id: str, wire: dict) -> dict: ...
    async def check_delivery(self, user_id: str) -> None: ...
    def start(self) -> None: ...
    def close(self) -> None: ...
    def plan(self, info: AgentInfo) -> LaunchPlan | None: ...
    def creating(self, plan: LaunchPlan) -> None: ...
    def created(self, plan: LaunchPlan, instance_id: str) -> None: ...
    def unknown(self, plan: LaunchPlan) -> None: ...
    def matches(self, plan: LaunchPlan, info: dict) -> bool: ...
    def protect(self, user_id: str, agent_type: str) -> bool: ...
    def deleting(self, info: AgentInfo) -> None: ...
    async def confirm_deleted(self, info: AgentInfo) -> None: ...
    def deleted(self, info: AgentInfo) -> None: ...
